DROP TABLE IF EXISTS frequencia;
DROP TABLE IF EXISTS notas;
DROP TABLE IF EXISTS estudantes;

CREATE TABLE estudantes (
    matricula VARCHAR(20) PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    turma VARCHAR(50) NOT NULL,
    turno VARCHAR(20) DEFAULT 'Manhã',
    situacao ENUM('Ativo','Inativo','Pendente') DEFAULT 'Ativo',
    data_nascimento DATE,
    nome_responsavel VARCHAR(100),
    email VARCHAR(100),
    telefone VARCHAR(20)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE notas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL,
    disciplina VARCHAR(100) NOT NULL,
    trimestre1 DECIMAL(4,2) DEFAULT 0.00,
    trimestre2 DECIMAL(4,2) DEFAULT 0.00,
    trimestre3 DECIMAL(4,2) DEFAULT 0.00,
    UNIQUE KEY aluno_disciplina (matricula, disciplina),
    FOREIGN KEY (matricula) REFERENCES estudantes(matricula) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE frequencia (
    id INT AUTO_INCREMENT PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL,
    disciplina VARCHAR(100) NOT NULL,
    faltas1 INT UNSIGNED DEFAULT 0,
    faltas2 INT UNSIGNED DEFAULT 0,
    faltas3 INT UNSIGNED DEFAULT 0,
    UNIQUE KEY aluno_disciplina (matricula, disciplina),
    FOREIGN KEY (matricula) REFERENCES estudantes(matricula) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


